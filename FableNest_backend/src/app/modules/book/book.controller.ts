import { Request, Response } from "express";
import catchAsync from "../../helpers/catchAsync";
import { BookService } from "./book.service";
import sendResponse from "../../helpers/sendResponse";
import status from "http-status";
import { getImageUrl } from "../../helpers/uploadFile";
import ApiError from "../../errors/ApiError";

export const BookController = {
  create: catchAsync(async (req: Request, res: Response) => {
    const { id: userId } = req.user;
    const files = req.files as {
      images?: Express.MulterS3.File[];
    };

    if (!files?.images || files.images.length === 0) {
      throw new ApiError(status.NOT_FOUND, "No images uploaded");
    }

    const reference_image_urls = await Promise.all(
      files.images.map((file) => getImageUrl(file)),
    );

    const result = await BookService.createBook(
      req.body,
      userId,
      reference_image_urls,
    );
    sendResponse(res, {
      success: true,
      statusCode: status.OK,
      message: "Book created Successfully!",
      data: result,
    });
  }),
  createRestBook: catchAsync(async (req: Request, res: Response) => {
    const { id: bookId } = req.params;
    const result = await BookService.createRestBook(bookId);
    sendResponse(res, {
      success: true,
      statusCode: status.OK,
      message: "Rest Book created Successfully!",
      data: result,
    });
  }),
  getAllBooks: catchAsync(async (req: Request, res: Response) => {
    const result = await BookService.getAllBooks(req.query);
    sendResponse(res, {
      success: true,
      statusCode: status.OK,
      message: "All books retrieved Successfully!",
      meta: result.meta,
      data: result.data,
    });
  }),

  saveTheBookIntoDb: catchAsync(async (req: Request, res: Response) => {
    const { id: userId, role } = req.user;
    const { id: bookId } = req.params;

    const result = await BookService.publishBook(bookId, userId, role);

    sendResponse(res, {
      success: true,
      statusCode: status.OK,
      message: "Book published Successfully!",
      data: result,
    });
  }),

  regenerateBook: catchAsync(async (req: Request, res: Response) => {
    const { bookId } = req.params;
    const { pageName } = req.body;

    const result = await BookService.regenerateBook(bookId, pageName);
    sendResponse(res, {
      success: true,
      statusCode: status.OK,
      message: "Book regenerated Successfully",
      data: result,
    });
  }),





  /// auto generate

  getAutoGeneratedDraftBooks: catchAsync(
    async (req: Request, res: Response) => {
      const result = await BookService.getAutoGeneratedDraftBooks();

      sendResponse(res, {
        success: true,
        statusCode: status.OK,
        message: "Auto generated draft books fetched successfully",
        data: result,
      });
    },
  ),

  toggleAutoGenerate: catchAsync(async (req: Request, res: Response) => {
    const { isEnabled } = req.body;

    const result = await BookService.toggleAutoGenerate(Boolean(isEnabled));

    sendResponse(res, {
      success: true,
      statusCode: status.OK,
      message: "Auto generate setting updated",
      data: result,
    });
  }),

  reviewAutoGeneratedBook: catchAsync(async (req: Request, res: Response) => {
    const { bookId } = req.params;

    const result = await BookService.reviewAutoGeneratedBook(bookId);

    sendResponse(res, {
      success: true,
      statusCode: status.OK,
      message: "Auto generated book fetched for review",
      data: result,
    });
  }),



  // get single book 

  getSingleBook: catchAsync(async (req: Request, res: Response) => {
    const { id: bookId } = req.params;
    const result = await BookService.getSingleBook(bookId);
    sendResponse(res, {
      success: true,
      statusCode: status.OK,
      message: "Single book fetched successfully",
      data: result,
    });
  }),

};
