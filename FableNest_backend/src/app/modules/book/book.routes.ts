import { Router } from "express";
import { BookController } from "./book.controller";
import auth from "../../middlewares/auth";
import validateRequest from "../../middlewares/validateRequest";
import { uploadFile } from "../../helpers/uploadFile";
import { parseBody } from "../../middlewares/parseBody";
import { bookValidations } from "./book.validation";

const router = Router();

router.post(
  "/create",
  auth(),
  uploadFile.uploadReferenceImage,
  parseBody,
  validateRequest(bookValidations.generateStorySchema),
  BookController.create,
);

router.post("/create/rest-book/:id", auth(), BookController.createRestBook);
router.get("/get-all", auth(), BookController.getAllBooks);

router.patch("/:id/publish", auth(), BookController.saveTheBookIntoDb);

router.patch("/:bookId/regenerate", auth(), BookController.regenerateBook);

// get single

router.get("/:id", auth(), BookController.getSingleBook);


// auto generate
router.patch(
  "/auto-generate/toggle",
  auth(),
  BookController.toggleAutoGenerate,
);
router.get(
  "/auto-generated/drafts",
  auth(),
  BookController.getAutoGeneratedDraftBooks,
);
router.get("/:bookId/review", auth(), BookController.reviewAutoGeneratedBook);

export const BookRoutes = router;
