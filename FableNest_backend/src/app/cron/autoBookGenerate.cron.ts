import axios from "axios";
import cron from "node-cron";
import config from "../../config";
import prisma from "../lib/prisma";
import { prepareFormData } from "../modules/book/book.utils";

let isRunning = false;

export const startAutoGenerateBookCron = () => {
  //   cron.schedule("* * * * *", async () => {
  cron.schedule(
    "5 0 * * *",
    async () => {
      if (isRunning) {
        console.log("⏳ Auto-generate already running, skipping...");
        return;
      }

      isRunning = true;

      try {
        // ✅ 1) check enable/disable switch
        let setting = await prisma.autoGenerateSetting.findFirst();

        if (!setting) {
          setting = await prisma.autoGenerateSetting.create({
            data: { isEnabled: true },
          });
        }

        if (!setting.isEnabled) {
          console.log("⏸️ Auto-generate cron skipped (disabled)");
          return;
        }

        console.log("🚀 Auto-generate book cron started");

        //  get past themes
        const lastBooks = await prisma.book.findMany({
          where: { isAutoGenerated: true },
          orderBy: { createdAt: "desc" },
          take: 5,
          select: { title: true },
        });

        const past_themes =
          lastBooks.length > 0
            ? lastBooks.map((b) => b.title).filter(Boolean)
            : ["none"];

        const past_characters = [["none"]];

        //  create_character
        const characterRes = await axios.post(
          `${config.ai_base_url}/create_character`,
          { past_characters, past_themes },
          { timeout: 600000 },
        );

        const c = characterRes.data;

        if (
          !c?.name ||
          !c?.age ||
          !c?.gender ||
          !c?.story_prompt ||
          !c?.image_url
        ) {
          throw new Error("Invalid create_character response");
        }

        // ✅ 4) generate_story (JSON)
        const storyRes = await axios.post(
          `${config.ai_base_url}/generate_story`,
          {
            gender: c.gender,
            name: c.name,
            age: Number(c.age),
            image_style: "ANIME",
            language: "English",
            user_input: c.story_prompt,
            image: c.image_url,
          },
          {
            headers: {
              accept: "application/json",
              "Content-Type": "application/json",
            },
            timeout: 600000,
          },
        );

        const normalized = storyRes.data?.data ?? storyRes.data;

        if (!normalized?.story || !normalized?.prompt) {
          throw new Error("Invalid generate_story response");
        }

        const { story, prompt, page_connections } = normalized;
        const pageConnections = page_connections ?? {};

        const sortedPages = Object.keys(story).sort(
          (a, b) => Number(a.split(" ")[1]) - Number(b.split(" ")[1]),
        );

        const admin = await prisma.user.findFirst({
          where: { OR: [{ role: "ADMIN" }, { role: "SUPER_ADMIN" }] },
          select: { id: true },
        });

        if (!admin?.id) {
          throw new Error("No ADMIN user found in database");
        }

        const gender =
          c.gender?.toLowerCase() === "girl"
            ? "Female"
            : c.gender?.toLowerCase() === "boy"
              ? "Male"
              : c.gender;

        const LAST_PAGE_NAME = "page 14";

        const pagesToCreate = sortedPages
          .filter((k) => k !== "page 0")
          .map((k) => ({
            name: k,
            content: story[k] || "",
            prompt: prompt?.[k] || "",
          }));

        const hasLastPageAlready = pagesToCreate.some(
          (p) => p.name === LAST_PAGE_NAME,
        );

        if (!hasLastPageAlready) {
          pagesToCreate.push({
            name: LAST_PAGE_NAME,
            content: "",
            prompt: prompt?.[LAST_PAGE_NAME] || "",
          });
        }

        const book = await prisma.book.create({
          data: {
            title: story["page 0"],
            characterName: c.name,
            characterAge: Number(c.age),
            gender,
            style: "ANIME",
            language: "English",
            userId: admin.id,

            reference_image_1: c.image_url,
            reference_image_2: null,
            reference_image_3: null,

            coverImagePrompt: prompt["page 0"],
            coverImageUrl: "PENDING",
            pageConnections: pageConnections,

            status: "DRAFT",
            isAutoGenerated: true,

            pages: {
              create: pagesToCreate,
            },
          },
        });

        console.log("✅ Auto draft book created:", book.id);

        const formData = await prepareFormData(book.id);

        const imgRes = await axios.post(
          `${config.ai_base_url}/generate_images_full?coverpage=no&sequential=yes`,
          formData,
          {
            headers: {
              ...formData.getHeaders(),
              accept: "application/json",
            },
            timeout: 6000000,
          },
        );

        const imageData = imgRes.data?.image_urls || imgRes.data;
        const pdfUrl = imgRes.data?.pdf_url || null;

        if (!Array.isArray(imageData)) {
          throw new Error("Invalid generate_images_full response format");
        }

        // update cover
        const coverPage = imageData.find((p: any) => p.name === "page 0");

        if (coverPage?.fullPageUrl) {
          await prisma.book.update({
            where: { id: book.id },
            data: {
              coverImageUrl: coverPage.fullPageUrl,
              pdfUrl,
            },
          });
          console.log("✅ Cover page updated successfully");
        }

        //  coloring pages update (page 12 & 13 are single fullPageUrl)
        const page12 = imageData.find((p: any) => p.name === "page 12");
        const page13 = imageData.find((p: any) => p.name === "page 13");

        if (page12?.fullPageUrl) {
          await prisma.bookPage.updateMany({
            where: { bookId: book.id, name: "page 12" },
            data: { fullPageUrl: page12.fullPageUrl },
          });
        }

        if (page13?.fullPageUrl) {
          await prisma.bookPage.updateMany({
            where: { bookId: book.id, name: "page 13" },
            data: { fullPageUrl: page13.fullPageUrl },
          });
        }

        console.log("✅ Coloring pages (12,13) updated");

        //  update rest pages INCLUDING page 14
        const pagesToUpdate = imageData.filter((p: any) => p.name !== "page 0");

        // skip 12 & 13 because already updated above
        const normalPages = pagesToUpdate.filter(
          (p: any) => p.name !== "page 12" && p.name !== "page 13",
        );

        if (normalPages.length > 0) {
          const BATCH_SIZE = 3;
          let successCount = 0;
          let failCount = 0;

          for (let i = 0; i < normalPages.length; i += BATCH_SIZE) {
            const batch = normalPages.slice(i, i + BATCH_SIZE);

            await prisma.$transaction(
              async (tx) => {
                for (const page of batch) {
                  const updateResult = await tx.bookPage.updateMany({
                    where: { bookId: book.id, name: page.name },
                    data: {
                      fullPageUrl: page.fullPageUrl || null,
                      leftUrl: page.leftUrl || null,
                      rightUrl: page.rightUrl || null,
                    },
                  });

                  if (updateResult.count > 0) successCount++;
                  else {
                    failCount++;
                    console.warn("❌ Page missing in DB:", page.name);
                  }
                }
              },
              { maxWait: 10000, timeout: 30000 },
            );
          }

          console.log(
            `✅ Pages updated: ${successCount} success, ${failCount} failed (total ${normalPages.length})`,
          );
        }

        // ✅ 11) update lastRunAt
        await prisma.autoGenerateSetting.update({
          where: { id: setting.id },
          data: { lastRunAt: new Date() },
        });

        console.log("✅ Auto-generate book finished successfully:", book.id);
      } catch (error) {
        console.error("❌ Auto-generate book cron failed:", error);
        console.log("AI error detail:", (error as any)?.response?.data);
      } finally {
        isRunning = false;
      }
    },
    {
      timezone: "Europe/Paris",
    },
  );

  console.log("🕒 Auto-generate book cron job started");
};
